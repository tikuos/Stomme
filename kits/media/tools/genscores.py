#!/usr/bin/env python3
"""
Bake the scores under assets/sounds into one C header.

Each <event>.score becomes an entry { "event", "text" } in TIKU_SCORES,
the text as written so a reader of the header sees the same lines as a
reader of the file.  Run by make with the directory as its argument and
the header on standard output.

Version: 0.01

Authors: Ambuj Varshney <ambuj@kinstugi-os.org>
"""
import os
import sys


def cstring(text):
    out = []
    for line in text.split('\n'):
        esc = line.replace('\\', '\\\\').replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return '\n'.join(out)


def main(argv):
    d = argv[0] if argv else 'assets/sounds'
    names = sorted(f[:-6] for f in os.listdir(d) if f.endswith('.score'))
    print('/* Generated by kits/media/tools/genscores.py from %s: do not edit. */' % d)
    print('static const struct {')
    print('    const char *name;')
    print('    const char *text;')
    print('} TIKU_SCORES[] = {')
    for n in names:
        with open(os.path.join(d, n + '.score'), encoding='utf-8') as f:
            text = f.read().rstrip('\n')
        print('    { "%s",' % n)
        print(cstring(text) + ' },')
    print('};')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
