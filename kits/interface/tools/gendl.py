#!/usr/bin/env python3
"""The display list's ops, generated from dl_ops.txt for both ends.

    gendl.py desktop dl_ops.txt   > kits/interface/tiku_dl_ops.h
    gendl.py board   dl_ops.txt   > board/gui/tiku_draw_ops.h

The desktop header carries the numbers, the payload lengths and where a
command's text starts, which tiku_dl.c reads and checks by.  The board
header carries a writer per op into a window's fixed buffer, with the
fields in wire order.  A row added to the table reaches both.
"""
import sys

SIZES = {"rect": 8, "i16": 2, "u16": 2, "u32": 4, "rgb": 4, "face": 1,
         "u8": 1}
TAILS = ("str", "strs", "blob16", "bytes")


def parse(path):
    ops = []
    for line in open(path):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        head, _, says = line.rpartition("  ")
        parts = head.split(None, 2)
        number, name = int(parts[0]), parts[1]
        fields = []
        if len(parts) > 2:
            for f in parts[2].split(","):
                kind, ident = f.split()
                fields.append((kind, ident))
        ops.append((number, name, fields, says.strip()))
    return ops


def fixed(fields):
    n = 0
    for kind, _ in fields:
        if kind in TAILS:
            return None
        n += SIZES[kind]
    return n


def head_len(fields):
    return sum(SIZES[k] for k, _ in fields if k not in TAILS)


def tail(fields):
    for kind, _ in fields:
        if kind in TAILS:
            return kind
    return None


def desktop(ops):
    out = []
    out.append("/*\n * TikuOS kits -- the foundation TikuDesktop and TikuTracker\n"
               " * both stand on.\n *\n * Authors: Ambuj Varshney <ambuj@tiku-os.org>\n"
               " *\n * tiku_dl_ops.h - the display list's ops, from dl_ops.txt.\n *\n"
               " * Generated by kits/interface/tools/gendl.py; `make check-dl`\n"
               " * proves it current.  Do not edit.\n *\n"
               " * SPDX-License-Identifier: Apache-2.0\n */\n"
               "#ifndef TIKU_DL_OPS_H_\n#define TIKU_DL_OPS_H_\n\n#include <stdint.h>\n\n")
    for number, name, _, _ in ops:
        out.append("#define TIKU_DL_OP_%-14s %du\n" % (name, number))
    out.append("\n/** @brief Every op's short name, for a file that speaks of them often. */\n"
               "#define TIKU_DL_OP_SHORT_NAMES \\\n")
    for i, (number, name, _, _) in enumerate(ops):
        sep = " \\" if i + 1 < len(ops) else ""
        out.append("    enum { OP_%s = %du };%s\n" % (name, number, sep))
    out.append("\n/** @brief A fixed op's payload length, or -1 when it carries a tail. */\n"
               "static inline int\ntiku_dl_op_fixed(uint16_t op)\n{\n    switch (op) {\n")
    for number, name, fields, _ in ops:
        f = fixed(fields)
        if f is not None:
            out.append("    case %du: return %d;\n" % (number, f))
    out.append("    default: return -1;\n    }\n}\n\n")
    out.append("/** @brief The least an op carrying text can be: its head and one\n"
               " *         terminator; -1 for an op that carries none. */\n"
               "static inline int\ntiku_dl_op_least(uint16_t op)\n{\n    switch (op) {\n")
    for number, name, fields, _ in ops:
        if tail(fields) in ("str", "strs"):
            out.append("    case %du: return %d;\n" % (number, head_len(fields) + 1))
    out.append("    default: return -1;\n    }\n}\n\n")
    out.append("/** @brief Where an op's text starts in its payload, or -1 for none. */\n"
               "static inline int\ntiku_dl_op_text_at(uint16_t op)\n{\n    switch (op) {\n")
    for number, name, fields, _ in ops:
        if tail(fields) in ("str", "strs"):
            out.append("    case %du: return %d;\n" % (number, head_len(fields)))
    out.append("    default: return -1;\n    }\n}\n\n")
    out.append("/** @brief The op's name, for a log. */\nstatic inline const char *\n"
               "tiku_dl_op_name(uint16_t op)\n{\n    switch (op) {\n")
    for number, name, _, _ in ops:
        out.append("    case %du: return \"%s\";\n" % (number, name.lower()))
    out.append("    default: return \"?\";\n    }\n}\n\n#endif /* TIKU_DL_OPS_H_ */\n")
    return "".join(out)


CARGS = {"rect": "int {n}_x, int {n}_y, int {n}_w, int {n}_h", "i16": "int {n}",
         "u16": "int {n}", "u32": "uint32_t {n}", "rgb": "uint32_t {n}",
         "face": "tiku_draw_face_t {n}", "u8": "unsigned {n}",
         "str": "const char *{n}", "strs": "const void *{n}, size_t {n}_len",
         "blob16": "const void *{n}, size_t {n}_len",
         "bytes": "const void *{n}, size_t {n}_len"}


def board(ops):
    out = []
    out.append("/*\n * TikuGUI -- a board's interface on the desktop.\n *\n"
               " * Authors: Ambuj Varshney <ambuj@tiku-os.org>\n *\n"
               " * tiku_draw_ops.h - a writer per op of the display list, from\n"
               " * dl_ops.txt, the fields in wire order.\n *\n"
               " * Generated by kits/interface/tools/gendl.py; `make check-dl` on the\n"
               " * desktop proves it current.  Do not edit.  Included by tiku_draw.c\n"
               " * after its byte helpers, and by tiku_draw.h for the prototypes.\n *\n"
               " * SPDX-License-Identifier: Apache-2.0\n */\n")
    out.append("#ifdef TIKU_DRAW_OPS_PROTOTYPES\n")
    for number, name, fields, _ in ops:
        args = ", ".join(CARGS[k].format(n=i) for k, i in fields)
        args = (", " + args) if args else ""
        out.append("/** @brief The %s op, its fields in wire order.  1 when written. */\n"
                   "int tiku_draw_%s(tiku_draw_window_t *win%s);\n" % (name.lower(), name.lower(), args))
    out.append("#endif\n\n#ifdef TIKU_DRAW_OPS_BODIES\n")
    for number, name, fields, _ in ops:
        args = ", ".join(CARGS[k].format(n=i) for k, i in fields)
        args = (", " + args) if args else ""
        head = head_len(fields)
        t = tail(fields)
        out.append("int\ntiku_draw_%s(tiku_draw_window_t *win%s)\n{\n" % (name.lower(), args))
        if t == "str":
            i = [i for k, i in fields if k == "str"][0]
            out.append("    size_t tail = (%s != NULL) ? strlen(%s) + 1u : 1u;\n" % (i, i))
        elif t == "blob16":
            i = [i for k, i in fields if k == "blob16"][0]
            out.append("    size_t tail = 2u + %s_len;\n" % i)
        elif t in ("bytes", "strs"):
            i = [i for k, i in fields if k in ("bytes", "strs")][0]
            out.append("    size_t tail = %s_len;\n" % i)
        else:
            out.append("    size_t tail = 0u;\n")
        out.append("    unsigned char *p = tiku_draw_op_begin(win, %du, %du + tail);\n"
                   "    size_t at = %du;\n\n    if (p == NULL) {\n        return 0;\n    }\n"
                   % (number, head, head))
        off = 0
        for kind, ident in fields:
            if kind == "rect":
                out.append("    tiku_draw_put16(p + %d, %s_x);\n    tiku_draw_put16(p + %d, %s_y);\n"
                           "    tiku_draw_put16(p + %d, %s_w);\n    tiku_draw_put16(p + %d, %s_h);\n"
                           % (off, ident, off + 2, ident, off + 4, ident, off + 6, ident))
            elif kind in ("i16", "u16"):
                out.append("    tiku_draw_put16(p + %d, %s);\n" % (off, ident))
            elif kind in ("u32", "rgb"):
                out.append("    tiku_draw_put32(p + %d, %s);\n" % (off, ident))
            elif kind in ("face", "u8"):
                out.append("    p[%d] = (unsigned char)%s;\n" % (off, ident))
            elif kind == "str":
                out.append("    memcpy(p + at, %s ? %s : \"\", tail);\n" % (ident, ident))
            elif kind == "blob16":
                out.append("    tiku_draw_put16(p + at, (int)%s_len);\n"
                           "    memcpy(p + at + 2, %s, %s_len);\n" % (ident, ident, ident))
            elif kind in ("bytes", "strs"):
                out.append("    memcpy(p + at, %s, %s_len);\n" % (ident, ident))
            if kind not in TAILS:
                off += SIZES[kind]
        out.append("    (void)at;\n    return 1;\n}\n\n")
    out.append("#endif\n")
    return "".join(out)


def main():
    which, path = sys.argv[1], sys.argv[2]
    ops = parse(path)
    sys.stdout.write(desktop(ops) if which == "desktop" else board(ops))


if __name__ == "__main__":
    main()
