#!/usr/bin/env python3
"""
Bake SASLprep's tables (RFC 4013) into a header for tiku_saslprep.c.

SASLprep is stringprep (RFC 3454) over Unicode 3.2: characters mapped to
nothing or to a space, NFKC as Unicode 3.2 had it (with Corrigendum 4's
five fixes, as ICU and CPython apply them), then what may not appear and
the rules for right-to-left text.  Python carries exactly that version of
the database (unicodedata.ucd_3_2_0) and RFC 3454's tables (stringprep),
frozen, so the header is made here at build time rather than kept in the
tree: some five thousand decompositions nobody should edit by hand.

Run: kits/support/tools/gensaslprep.py > build/generated/tiku_saslprep_tables.h

Version: 0.01

Authors: Ambuj Varshney <ambuj@kinstugi-os.org>
"""

import stringprep
import sys
import unicodedata

U = unicodedata.ucd_3_2_0
HANGUL = range(0xAC00, 0xAC00 + 11172)          # decomposed by rule
SURROGATES = range(0xD800, 0xE000)
CORRIGENDUM4 = (0x2F868, 0x2F874, 0x2F91F, 0x2F95F, 0x2F9BF)


def chars():
    """Every code point but the surrogates and Hangul syllables."""
    for cp in range(0x110000):
        if cp not in SURROGATES and cp not in HANGUL:
            yield cp


def decompositions():
    """Each character NFKD changes, and the code points it becomes."""
    out = []
    for cp in chars():
        nfkd = U.normalize('NFKD', chr(cp))
        if nfkd != chr(cp):
            out.append((cp, [ord(c) for c in nfkd]))
    return out


def pairs():
    """The canonical pairs that compose again (not excluded), and what
    each makes; Corrigendum 4's five decompose to one and make none."""
    out = []
    for cp in chars():
        d = U.decomposition(chr(cp))
        if not d or d.startswith('<') or cp in CORRIGENDUM4:
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) == 2 and \
           U.normalize('NFC', chr(parts[0]) + chr(parts[1])) == chr(cp):
            out.append((parts[0] << 21 | parts[1], cp))
    return sorted(out)


def runs(value):
    """Runs of code points with one value that is not 0 or False: first,
    last and the value."""
    out = []
    for cp in range(0x110000):
        v = 0 if cp in SURROGATES else value(chr(cp))
        if v and out and out[-1][1] == cp - 1 and out[-1][2] == v:
            out[-1][1] = cp
        elif v:
            out.append([cp, cp, v])
    return out


def prohibited(c):
    """RFC 4013's section 2.3: tables C.1.2, C.2.1, C.2.2, C.3 to C.9."""
    return (stringprep.in_table_c12(c) or stringprep.in_table_c21_c22(c) or
            stringprep.in_table_c3(c) or stringprep.in_table_c4(c) or
            stringprep.in_table_c5(c) or stringprep.in_table_c6(c) or
            stringprep.in_table_c7(c) or stringprep.in_table_c8(c) or
            stringprep.in_table_c9(c))


def array(ctype, name, items, fmt, per):
    """A C array of @items, @per to a line."""
    lines = ['static const %s %s[%d] = {' % (ctype, name, len(items))]
    for i in range(0, len(items), per):
        lines.append('    ' + ', '.join(fmt % x for x in items[i:i + per]) +
                     ',')
    lines.append('};')
    return '\n'.join(lines)


def ranges(name, table):
    """A table of first-last pairs, three to a line."""
    flat = [(r[0], r[1]) for r in table]
    lines = ['static const uint32_t %s[%d][2] = {' % (name, len(flat))]
    for i in range(0, len(flat), 3):
        lines.append('    ' + ' '.join('{0x%05X, 0x%05X},' % r
                                       for r in flat[i:i + 3]))
    lines.append('};')
    return '\n'.join(lines)


def main():
    dec = decompositions()
    at, to = [], []
    for cp, parts in dec:
        at.append(len(to))
        to.extend(parts)
    out = ['/* GENERATED by kits/support/tools/gensaslprep.py from Python\'s',
           ' * Unicode 3.2 database and RFC 3454\'s tables: edit that. */',
           '',
           '/* Each character NFKD changes: its code point << 5 | how many',
           ' * it becomes; sorted.  Where they start in sp_to. */',
           array('uint32_t', 'sp_dec',
                 [cp << 5 | len(p) for cp, p in dec], '0x%08X', 6),
           array('uint16_t', 'sp_at', at, '%d', 12),
           array('uint32_t', 'sp_to', to, '0x%05X', 8),
           '',
           '/* Canonical pairs that compose: first << 21 | second, sorted,',
           ' * and what each makes. */',
           array('uint64_t', 'sp_pair', [k for k, v in pairs()],
                 '0x%011XULL', 4),
           array('uint32_t', 'sp_pair_to', [v for k, v in pairs()],
                 '0x%05X', 8),
           '',
           '/* Combining classes not 0: first, last, class. */',
           'static const uint32_t sp_ccc[%d][3] = {' %
           len(runs(U.combining))]
    cr = runs(U.combining)
    for i in range(0, len(cr), 3):
        out.append('    ' + ' '.join('{0x%05X, 0x%05X, %d},' % tuple(r)
                                     for r in cr[i:i + 3]))
    out += ['};', '',
            '/* Mapped to nothing (B.1), to a space (C.1.2); prohibited;',
            ' * right to left (D.1) and left to right (D.2). */',
            ranges('sp_nothing', runs(stringprep.in_table_b1)),
            ranges('sp_space', runs(stringprep.in_table_c12)),
            ranges('sp_prohibited', runs(prohibited)),
            ranges('sp_randal', runs(stringprep.in_table_d1)),
            ranges('sp_lcat', runs(stringprep.in_table_d2)), '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
