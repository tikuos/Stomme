#!/usr/bin/env python3
"""
Bake the English catalogue into the binary.

The words live in strings/en.xml, which is the one place they are written;
this turns that file into a compiled-in fallback so the interface has
words even on a device with no strings folder at all.  Translations are
separate <lang>.xml files, read over this one at runtime.

The header it writes is made by the build, into build/generated/, for the
support kit's tiku_strings.c to include: the catalogue is the shells'
to write and the kit's to bake, and a baked copy in the tree would only
learn to disagree with the XML.

Run: kits/support/tools/genstrings.py assets/strings/en.xml > build/generated/tiku_strings_default.h

Version: 0.01

Authors: Ambuj Varshney <ambuj@kinstugi-os.org>
"""

import sys
import xml.etree.ElementTree as ET


def c_escape(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20:
            out.append('\\%03o' % ord(ch))
        else:
            out.append(ch)            # UTF-8 bytes pass straight through
    return ''.join(out)


def main():
    if len(sys.argv) < 2:
        sys.stderr.write("usage: genstrings.py strings/en.xml\n")
        return 2
    tree = ET.parse(sys.argv[1])
    root = tree.getroot()
    pairs = {}
    for node in root.findall('string'):
        key = node.get('name')
        if not key:
            continue
        pairs[key] = node.text if node.text is not None else ''
    keys = sorted(pairs)

    out = sys.stdout
    out.write("/*\n"
              ' * KintsugiOS v0.01 kits -- the foundation KintsugiDesktop and KintsugiTracker\n'
              " * both stand on.\n"
              " *\n"
              ' * Authors: Ambuj Varshney <ambuj@kinstugi-os.org>\n'
              " *\n"
              " * tiku_strings_default.h - the baked English catalogue.\n"
              " *\n"
              " * GENERATED by the build, kits/support/tools/genstrings.py over\n"
              " * assets/strings/en.xml -- not kept in the tree; edit the XML\n"
              " * and build.\n"
              " *\n"
              " * SPDX-License-Identifier: Apache-2.0\n"
              " */\n"
              "#ifndef TIKU_STRINGS_DEFAULT_H_\n"
              "#define TIKU_STRINGS_DEFAULT_H_\n\n")
    out.write("typedef struct {\n"
              "    const char *key;\n"
              "    const char *value;\n"
              "} tiku_str_def_t;\n\n")
    out.write("/* Sorted by key, so a lookup is a binary search. */\n")
    out.write("static const tiku_str_def_t tiku_str_defaults[] = {\n")
    for k in keys:
        out.write('    { "%s", "%s" },\n' % (c_escape(k), c_escape(pairs[k])))
    out.write("};\n\n")
    out.write("static const int tiku_str_default_count =\n"
              "    (int)(sizeof tiku_str_defaults /\n"
              "          sizeof tiku_str_defaults[0]);\n\n")
    out.write("#endif /* TIKU_STRINGS_DEFAULT_H_ */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
